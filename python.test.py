while True:
    question=input("Какая группа экстремофилов Вас интересует? (или напишите 'выход' для завершения работы)\n ").lower()
    if "выход" in question:
        print("Благодарим за использование справочника! До встречи")
        break
    elif "термофил" in question:
        print("Термофилы - это организмы, приспособленные к жизни при постоянно высоких температурах (обычно выше +40... +45 градусов), которые губительны для большинства других форм жизни.")
    elif "галофил" in question:
        print("Галофилы - это организмы, которые обитают в средах с высокой концентрацией соли (NaCl)")
    elif "психрофил" in question or "криофил" in question:
        print("Психрофилы (или криофилы) - это организмы, которые нормально существуют и размножаются при низких температурах")
    elif "ацидофил" in question:
        print("Ацидофилы - это организмы, процветающие в условиях повышенной кислотности среды")
    elif "алкалифил" in question:
        print("Алкалифилы — это микроорганизмы, которые оптимально растут в сильнощелочной среде, с уровнем pH примерно от 8,5 до 11 и выше")
    else:
        print("Хм... Попробуйте задать другой вопрос")
